"""Create a SHA-256 requirements lock from exact predownloaded wheels (stdlib only)."""
import argparse
from email.parser import BytesParser
import hashlib
from pathlib import Path
import re
import zipfile


TORCH_URL = "https://download-r2.pytorch.org/whl/cpu/torch-2.15.0%2Bcpu-cp313-cp313-win_amd64.whl"
TORCH_SHA = "086f79c78c941b428410dc15f898ce2420a4580ae6983ea314692d71ce76c619"


def canonical(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wheel-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    entries = {}
    for path in sorted(args.wheel_dir.glob("*.whl")):
        with zipfile.ZipFile(path) as wheel:
            metadata = [name for name in wheel.namelist() if name.endswith(".dist-info/METADATA") and name.count("/") == 1]
            if len(metadata) != 1:
                raise ValueError(f"Ambiguous wheel metadata: {path}")
            message = BytesParser().parsebytes(wheel.read(metadata[0]))
        name, version = canonical(message["Name"]), message["Version"]
        if name in entries:
            raise ValueError(f"Duplicate platform/version wheel: {name}")
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if name == "torch" and digest != TORCH_SHA:
            raise ValueError("Torch wheel differs from the official pinned CPU wheel hash")
        requirement = f"torch @ {TORCH_URL}" if name == "torch" else f"{name}=={version}"
        entries[name] = f"{requirement} --hash=sha256:{digest}\n"
    if not entries or "torch" not in entries:
        raise ValueError("No complete baseline wheel set")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        "# Verified Windows x64 / CPython 3.13.5 / CPU; generated by tools/lock_wheels.py.\n"
        "# All direct/transitive runtime dependencies are exact wheel hashes.\n"
        "--require-hashes\n--only-binary=:all:\n" + "".join(entries[name] for name in sorted(entries)), encoding="utf-8")
    print(f"Locked {len(entries)} distributions: {args.output}")


if __name__ == "__main__":
    main()
